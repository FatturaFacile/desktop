using System.Text;
using FatturaFacile.Application.Taxation;
using FatturaFacile.Domain.Entities;
using Xunit;

namespace FatturaFacile.UnitTests;

/// <summary>
/// Tests of the LIPE checks: the partita IVA check digit, the ministerial rules, the structural schema validation and the data
/// built from a VAT return.
/// </summary>
public sealed class LipeComplianceTests
{
    private const string ValidVat = "01234567897";

    /// <summary>
    /// Well-formed partite IVA with a correct check digit pass; everything else fails.
    /// </summary>
    /// <param name="value">The number.</param>
    /// <param name="expected">Whether it is valid.</param>
    [Theory]
    [InlineData("01234567897", true)]
    [InlineData("12345678903", true)]
    [InlineData("00743110157", true)]
    [InlineData("12345678901", false)]
    [InlineData("1234567890", false)]
    [InlineData("0123456789A", false)]
    [InlineData("", false)]
    [InlineData(null, false)]
    public void PartitaIva_ChecksFormatAndCheckDigit(string? value, bool expected) => Assert.Equal(expected, PartitaIva.IsValid(value));

    /// <summary>
    /// Consistent data breaks no rule, quarterly or monthly.
    /// </summary>
    [Fact]
    public void Check_ConsistentData_HasNoViolations()
    {
        Assert.Empty(LipeRules.Check(Data()));
        Assert.Empty(LipeRules.Check(Data(month: 3, quarter: null)));
    }

    /// <summary>
    /// Each ministerial rule reports its code.
    /// </summary>
    [Fact]
    public void Check_ReportsEachViolatedRule()
    {
        var codes = LipeRules.Check(new LipeData
        {
            TaxCode = "123",
            VatNumber = "12345678901",
            Year = 2010,
            Month = 3,
            Quarter = 1,
            DeclarantTaxCode = "XX",
            ActiveOperations = -1m,
            OutputVat = 100m,
            InputVat = 10m,
            Payable = 5m,
        });

        Assert.Contains("tax_code_invalid", codes, StringComparer.Ordinal);
        Assert.Contains("vat_number_invalid", codes, StringComparer.Ordinal);
        Assert.Contains("declarant_tax_code_invalid", codes, StringComparer.Ordinal);
        Assert.Contains("year_invalid", codes, StringComparer.Ordinal);
        Assert.Contains("period_invalid", codes, StringComparer.Ordinal);
        Assert.Contains("negative_amount", codes, StringComparer.Ordinal);
        Assert.Contains("payable_inconsistent", codes, StringComparer.Ordinal);
    }

    /// <summary>
    /// A credit that does not follow from the figures is reported.
    /// </summary>
    [Fact]
    public void Check_InconsistentCredit_IsReported()
    {
        var codes = LipeRules.Check(Data(output: 100m, input: 300m, payable: -50m));

        Assert.Contains("credit_inconsistent", codes, StringComparer.Ordinal);
    }

    /// <summary>
    /// The XML generated by the builder passes the structural schema validation.
    /// </summary>
    [Fact]
    public void Xsd_GeneratedFile_IsValid()
    {
        var xml = LipeXmlBuilder.Build(Data());

        Assert.Empty(LipeXsdValidator.Validate(xml));
    }

    /// <summary>
    /// A file with a missing mandatory element or a wrong amount format fails with an xsd error.
    /// </summary>
    [Fact]
    public void Xsd_BrokenFile_ReportsErrors()
    {
        var text = Encoding.UTF8.GetString(LipeXmlBuilder.Build(Data()));
        var withoutSignature = text.Replace("<iv:FirmaDichiarazione>1</iv:FirmaDichiarazione>", string.Empty, StringComparison.Ordinal);
        var badAmount = text.Replace("1000,00", "1000.5", StringComparison.Ordinal);

        Assert.NotEmpty(LipeXsdValidator.Validate(Encoding.UTF8.GetBytes(withoutSignature)));
        var errors = LipeXsdValidator.Validate(Encoding.UTF8.GetBytes(badAmount));
        Assert.NotEmpty(errors);
        Assert.All(errors, static e => Assert.StartsWith("xsd:", e, StringComparison.Ordinal));
        Assert.NotEmpty(LipeXsdValidator.Validate("<not-xml"u8));
    }

    /// <summary>
    /// The data is built from the return and the company: VAT number without the country prefix, quarter of a quarterly period and
    /// no declarant when it is the company itself.
    /// </summary>
    [Fact]
    public void Factory_BuildsTheDataFromTheReturnAndTheCompany()
    {
        VatReturn vatReturn = new()
        {
            Country = "IT",
            PeriodFrom = new DateTime(2027, 4, 1, 0, 0, 0, DateTimeKind.Unspecified),
            PeriodTo = new DateTime(2027, 6, 30, 0, 0, 0, DateTimeKind.Unspecified),
            TaxableTurnover = 1000m,
            OutputVat = 220m,
            InputVat = 100m,
            Payable = 120m,
        };
        Tenant company = new() { VatNumber = "IT 01234567897", FiscalCode = null, DeclarantFiscalCode = "01234567897", DeclarantRoleCode = "1" };

        var data = LipeDataFactory.Create(vatReturn, company, passiveOperations: 500m);

        Assert.Equal(ValidVat, data.VatNumber);
        Assert.Equal(ValidVat, data.TaxCode);
        Assert.Equal(2027, data.Year);
        Assert.Null(data.Month);
        Assert.Equal(2, data.Quarter);
        Assert.Null(data.DeclarantTaxCode);
        Assert.Equal(500m, data.PassiveOperations);
        Assert.Empty(LipeRules.Check(data));
    }

    private static LipeData Data(int? month = null, int? quarter = 1, decimal output = 220m, decimal input = 100m, decimal payable = 120m) => new()
    {
        TaxCode = ValidVat,
        VatNumber = ValidVat,
        Year = 2027,
        Month = month,
        Quarter = quarter,
        ActiveOperations = 1000m,
        PassiveOperations = 500m,
        OutputVat = output,
        InputVat = input,
        Payable = payable,
    };
}
